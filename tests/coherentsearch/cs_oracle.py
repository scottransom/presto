"""A plain NumPy statement of CoherentSearch.jl's production search, stage by stage.

This is the executable specification the C ``coherentsearch`` is written against. It
is deliberately simple and slow: every quantity is computed directly in float64 from
its definition, with 0-based indices, and none of the production path's caching,
tabulation, grouping or batching.  ``tests/test_coherentsearch.py`` checks it against
the Julia fixtures in ``fixtures/`` (generated by ``gen_fixtures.jl``), so any
difference between what the Julia code does and what is written here fails a test.

The conventions it pins down, which are easy to get wrong in a port:

* **Trial grid.**  Global trial ``t`` sits at fundamental Fourier frequency
  ``r_t = r_lo + t * lodr``, with ``lodr = hidr / nharms`` held as an exact rational
  ``pnum / q``.  Harmonic ``h`` is at ``h * r_t``, split into an integer bin and a
  fractional offset with exact integer arithmetic (``_harmonic_bin``).
* **Interpolation** (Eqn. 30 of Ransom, Eikerenberry & Middleditch 2002, truncated to
  ``m`` bins): the ``m`` bins ``floor(h r) + j`` for ``j = 1 - m/2 ... m/2`` are summed
  with real weights ``1 / (dr - j)`` and multiplied by ``conj(sin(pi dr) e^{i pi dr}) /
  pi``.  The ``.fft`` element 0 (DC real, Nyquist imaginary) is used as is if a
  window reaches it.
* **Which harmonics a chunk uses.**  A harmonic is filled for a whole chunk only if it
  fits at both the chunk's first and last trial (``harmonic_fits``); otherwise its
  row stays zero.  The filled set need not be a prefix (the lowest harmonics do not
  fit at the very bottom of the band).
* **Profiles** are the unnormalised complex-to-real inverse FFT of the harmonic stack
  (row 0 = DC = 0), ``nbins = 2 * Hk`` long.  Decimation ``k`` uses rows ``0, k, 2k,
  ..., Hk k``.
* **Metric**: the peak over a pruned boxcar width bank of the wrapped boxcar sum,
  normalised by a per-chunk noise scale (analytic, from the filled harmonics, or a
  MAD) and a per-width band-limited-noise ``shape`` factor.
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from pathlib import Path

import numpy as np

SIGMA_CAP = 8192  # CoherentSearch.jl _BOXCAR_SIGMA_SAMPLES
LADDER_WMAX = 6  # CoherentSearch.jl _LADDER_WMAX


@dataclass(frozen=True)
class Params:
    """Search parameters (the ``coherent_search`` CLI defaults)."""

    nharms: int = 60
    m: int = 16
    hidr: float = 0.5
    maxdecim: int = 6
    boxcar_fsp: float = 1.5
    boxcar_maxfrac: float = 0.3

    @property
    def lodr_frac(self) -> Fraction:
        """The trial step ``hidr / nharms`` as an exact fraction."""
        return Fraction(self.hidr).limit_denominator(1 << 16) / self.nharms

    @property
    def lodr(self) -> float:
        """The trial step in Fourier bins."""
        return self.hidr / self.nharms

    @property
    def decimations(self) -> list[int]:
        """Decimation factors searched: ``k`` with at least two harmonics left."""
        return [k for k in range(1, max(1, self.maxdecim) + 1) if self.nharms // k >= 2]


@dataclass
class FFTData:
    """A PRESTO ``.fft`` file: packed complex64 amplitudes plus its length."""

    amps: np.ndarray  # complex128 copy of the file's complex64 values
    N: int  # time-series length from the .inf
    T: float  # observation length (s)


def read_fft(path: str | Path) -> FFTData:
    """Read a PRESTO ``.fft`` file and the ``N`` and ``dt`` from its ``.inf``.

    Parameters
    ----------
    path : str or Path
        The ``.fft`` file.  Its ``.inf`` must sit beside it.

    Returns
    -------
    FFTData
        The amplitudes (widened to complex128) and the time-series length.
    """
    path = Path(path)
    amps = np.fromfile(path, dtype="<c8").astype(np.complex128)
    N = dt = None
    for line in path.with_suffix(".inf").read_text().splitlines():
        if line.startswith(" Number of bins"):
            N = int(line.split("=")[-1])
        elif line.startswith(" Width of each time series bin"):
            dt = float(line.split("=")[-1])
    if N is None or dt is None:
        raise ValueError(f"{path}: .inf lacks N or dt")
    return FFTData(amps, N, N * dt)


class HarmonicGrid:
    """Exact bin bookkeeping for harmonic ``h`` on the trial grid starting at ``r_lo``.

    Mirrors CoherentSearch.jl's ``DirectPlan``: ``h * r_lo`` is split once into
    ``rfloor0 + dr0``, and trial ``t`` adds ``h * t * pnum / q`` exactly.
    """

    def __init__(self, h: int, r_lo: float, params: Params):
        lodr = params.lodr_frac
        self.h = h
        self.pnum, self.q = lodr.numerator, lodr.denominator
        hr = h * float(r_lo)
        self.rfloor0 = int(np.floor(hr))
        self.dr0 = hr - self.rfloor0
        self.m2 = params.m // 2

    def at(self, t: int) -> tuple[int, int, float]:
        """Return ``(nyq_bin, floor_bin, dr)`` for global trial ``t``.

        ``floor_bin`` is ``floor(h * r_t)``; ``nyq_bin`` is the same without the carry
        from the fractional part, which is what the Nyquist test uses (as in Julia).
        """
        qint, res = divmod(t * self.h * self.pnum, self.q)
        u = self.dr0 + res / self.q
        carry = 1 if u >= 1.0 else 0
        dr = u - 1.0 if carry else u
        return self.rfloor0 + qint, self.rfloor0 + qint + carry, dr

    def fits(self, t: int, namps: int, N: int) -> bool:
        """Whether this harmonic has a full ``m``-bin window below Nyquist at trial ``t``."""
        nyq_bin, fb, _ = self.at(t)
        return fb + 1 - self.m2 >= 0 and fb + self.m2 <= namps - 1 and nyq_bin < N // 2


def interp(amps: np.ndarray, fb: int, dr: float, m: int) -> complex:
    """Exact ``m``-bin Fourier interpolation at ``fb + dr`` (Eqn. 30).

    Parameters
    ----------
    amps : numpy.ndarray
        The complex amplitudes.
    fb : int
        ``floor(r)``.
    dr : float
        ``r - floor(r)``, in [0, 1).
    m : int
        Number of bins summed (even).

    Returns
    -------
    complex
        The interpolated amplitude.
    """
    m2 = m // 2
    if dr == 0.0:
        return complex(amps[fb])
    j = np.arange(1 - m2, m2 + 1)
    s = np.sum(amps[fb + j] / (dr - j))
    return complex(np.conj(np.sin(np.pi * dr) * np.exp(1j * np.pi * dr) / np.pi) * s)


def chunk_filled(
    fft: FFTData, params: Params, r_lo: float, t0: int, n: int
) -> np.ndarray:
    """Which harmonics fit at both the first and last trial of a chunk.

    Returns
    -------
    numpy.ndarray
        bool, shape ``(nharms + 1,)``, indexed by harmonic number (index 0 unused).
    """
    filled = np.zeros(params.nharms + 1, dtype=bool)
    for h in range(1, params.nharms + 1):
        g = HarmonicGrid(h, r_lo, params)
        filled[h] = g.fits(t0, len(fft.amps), fft.N) and g.fits(
            t0 + n - 1, len(fft.amps), fft.N
        )
    return filled


def trial_stack(
    fft: FFTData, params: Params, r_lo: float, t: int, filled: np.ndarray
) -> np.ndarray:
    """The harmonic stack of global trial ``t``: complex128, ``nharms + 1`` long."""
    stack = np.zeros(params.nharms + 1, dtype=np.complex128)
    for h in np.flatnonzero(filled):
        _, fb, dr = HarmonicGrid(int(h), r_lo, params).at(t)
        stack[h] = interp(fft.amps, fb, dr, params.m)
    return stack


def chunk_harmonics(
    fft: FFTData, params: Params, r_lo: float, t0: int, n: int
) -> tuple[np.ndarray, np.ndarray]:
    """Interpolated harmonic stacks for trials ``t0 .. t0+n-1``.

    Returns
    -------
    ftprofs : numpy.ndarray
        complex128, shape ``(n, nharms + 1)``: row 0 (DC) zero, unfilled rows zero.
    filled : numpy.ndarray
        bool, shape ``(nharms + 1,)``, indexed by harmonic number (index 0 unused).
    """
    filled = chunk_filled(fft, params, r_lo, t0, n)
    ftprofs = np.array(
        [trial_stack(fft, params, r_lo, t0 + j, filled) for j in range(n)]
    )
    return ftprofs, filled


def profiles(ftprofs: np.ndarray, k: int, nharms: int) -> np.ndarray:
    """Unnormalised inverse-FFT profiles of the decimation-``k`` harmonic stacks.

    Returns
    -------
    numpy.ndarray
        float64, shape ``(n, 2 * (nharms // k))``.
    """
    Hk = nharms // k
    return np.fft.irfft(ftprofs[:, 0 : Hk * k + 1 : k], n=2 * Hk, axis=1) * (2 * Hk)


def boxcar_widths(nbins: int, fsp: float = 1.5, maxfrac: float = 0.3) -> list[int]:
    """Geometric boxcar width bank ``w_{i+1} = max(floor(fsp w_i), w_i + 1)``."""
    wmax = min(max(1, int(np.floor(maxfrac * nbins))), nbins - 1)
    ws, w = [], 1
    while w <= wmax:
        ws.append(w)
        w = max(int(np.floor(fsp * w)), w + 1)
    return ws


def ladder_boxcar_widths(nbins: int, k: int, params: Params) -> list[int]:
    """The width bank for decimation ``k``, pruned against the rest of the ladder."""
    ws = boxcar_widths(nbins, params.boxcar_fsp, params.boxcar_maxfrac)
    ks = sorted(params.decimations)
    if len(ks) <= 1:
        return ws
    if not all(ks[i + 1] <= (LADDER_WMAX // 2) * ks[i] for i in range(len(ks) - 1)):
        return ws
    kmin, kmax = ks[0], ks[-1]
    pruned = [
        w for w in ws if (w >= 2 or k == kmin) and (w <= LADDER_WMAX or k == kmax)
    ]
    return pruned or ws


def analytic_sigma(filled: np.ndarray, k: int, Hk: int) -> float:
    """Closed-form per-bin noise scale for unit-mean-power input."""
    nlow = sum(bool(filled[j * k]) for j in range(1, Hk))
    nnyq = 1 if filled[Hk * k] else 0
    if nlow + nnyq < 1:
        return 0.0
    return float(np.sqrt(2 * nlow + 0.5 * nnyq))


def boxcar_shape(filled: np.ndarray, k: int, Hk: int, widths: list[int]) -> np.ndarray:
    """Per-width ``sigma / sd(S_w)`` for band-limited (correlated-bin) noise."""
    nbins = 2 * Hk
    sigma = analytic_sigma(filled, k, Hk)
    shape = np.zeros(len(widths))
    for i, w in enumerate(widths):
        v = 0.0
        for j in range(1, Hk):
            if filled[j * k]:
                d = np.sin(np.pi * j * w / nbins) / np.sin(np.pi * j / nbins)
                v += 2 * d * d
        if filled[Hk * k]:
            d = np.sin(np.pi * w / 2)
            v += 0.5 * d * d
        shape[i] = sigma / np.sqrt(v) if (sigma > 0 and v > 0) else 0.0
    return shape


def measured_sigma(profs: np.ndarray, nvalid: int, cap: int = SIGMA_CAP) -> float:
    """``1.4826 * median(|x|)`` over (a whole-profile subsample of) the chunk.

    Parameters
    ----------
    profs : numpy.ndarray
        Shape ``(n, nbins)``; only the first ``nvalid`` profiles are used.
    nvalid : int
        Number of valid (leading) profiles.
    cap : int
        Most samples to use.  Above it, ``cap // nbins`` whole profiles are taken,
        evenly spaced, and the last one truncated to fit.

    Returns
    -------
    float
        The noise scale, or 0 for an empty block.
    """
    nbins = profs.shape[1]
    if nbins * nvalid == 0:
        return 0.0
    if nbins * nvalid <= cap:
        x = profs[:nvalid].ravel()
    else:
        ncol = min(nvalid, max(1, cap // nbins))
        parts, ns = [], 0
        for c in range(ncol):
            j = (c * nvalid) // ncol
            take = min(nbins, cap - ns)
            if take == 0:
                break
            parts.append(profs[j, :take])
            ns += take
        x = np.concatenate(parts)
    return 1.4826 * float(np.median(np.abs(x)))


def boxcar_metric(
    prof: np.ndarray, widths: list[int], sigma: float, shape: np.ndarray
) -> float:
    """Peak boxcar matched-filter S/N of one profile.

    ``max_{w,p} (sum_{i=p}^{p+w-1} P_i - (w/nbins) sum_i P_i) * shape_w / sigma``, with
    the boxcar wrapping around the end of the profile.  Zero if ``sigma <= 0``.
    """
    if sigma <= 0:
        return 0.0
    nbins = len(prof)
    wmax = widths[-1]
    psum = np.concatenate(([0.0], np.cumsum(np.concatenate((prof, prof[:wmax])))))
    stot = psum[nbins]
    best = -np.inf
    for w, s in zip(widths, shape):
        mx = np.max(psum[w : w + nbins] - psum[0:nbins])
        best = max(best, (mx - (w / nbins) * stot) * (s / sigma))
    return float(best)


@dataclass
class KResult:
    """Everything the metric stage computes for one decimation of one chunk."""

    Hk: int
    widths: list[int]
    nvalid: int
    sigma_analytic: float
    sigma_measured: float
    shape: np.ndarray
    profs: np.ndarray
    metric_analytic: np.ndarray
    metric_measured: np.ndarray


def chunk_metrics(
    fft: FFTData, params: Params, r_lo: float, t0: int, n: int
) -> tuple[np.ndarray, np.ndarray, dict[int, KResult]]:
    """Run every stage for one chunk.

    Returns
    -------
    ftprofs, filled
        As from :func:`chunk_harmonics`.
    results : dict
        :class:`KResult` per decimation factor ``k``.
    """
    ftprofs, filled = chunk_harmonics(fft, params, r_lo, t0, n)
    rstart = r_lo + t0 * params.lodr
    out = {}
    for k in params.decimations:
        Hk = params.nharms // k
        nbins = 2 * Hk
        widths = ladder_boxcar_widths(nbins, k, params)
        profs = profiles(ftprofs, k, params.nharms)
        if k == 1:
            nvalid = n
        else:
            nvalid = sum(k * (rstart + j * params.lodr) < fft.N / 2 for j in range(n))
        sa = analytic_sigma(filled, k, Hk)
        sm = measured_sigma(profs, nvalid)
        shape = boxcar_shape(filled, k, Hk, widths)
        ma = np.array(
            [boxcar_metric(profs[j], widths, sa, shape) for j in range(nvalid)]
        )
        mm = np.array(
            [boxcar_metric(profs[j], widths, sm, shape) for j in range(nvalid)]
        )
        out[k] = KResult(Hk, widths, nvalid, sa, sm, shape, profs, ma, mm)
    return ftprofs, filled, out


def chunk_starts(
    fft: FFTData, params: Params, r_lo: float, total: int, nprof: int
) -> list[int]:
    """First global trial of every chunk of a search over ``total`` trials.

    The regular ``nprof`` grid plus a forced split wherever any harmonic starts or
    stops fitting, so that one set of filled harmonics is right for a whole chunk.
    """
    namps = len(fft.amps)
    starts = set(range(0, total, nprof))
    for h in range(1, params.nharms + 1):
        g = HarmonicGrid(h, r_lo, params)

        def lo_ok(t: int, g: HarmonicGrid = g) -> bool:
            return g.at(t)[1] + 1 - g.m2 >= 0

        def hi_ok(t: int, g: HarmonicGrid = g) -> bool:
            nyq_bin, fb, _ = g.at(t)
            return fb + g.m2 <= namps - 1 and nyq_bin < fft.N // 2

        a = _first(lo_ok, total, want=True)
        b = _first(hi_ok, total, want=False)
        starts.update(x for x in (a, b) if 0 < x < total)
    return sorted(starts)


def _first(pred, total: int, want: bool) -> int:
    """First ``t`` in ``0..total-1`` with ``pred(t) == want`` for a monotone ``pred``."""
    if total < 1:
        return total
    if pred(0) == want:
        return 0
    if pred(total - 1) != want:
        return total
    lo, hi = 0, total - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if pred(mid) == want:
            hi = mid
        else:
            lo = mid
    return hi
